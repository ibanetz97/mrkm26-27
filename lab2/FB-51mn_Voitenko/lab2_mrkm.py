import random
import secrets
import time
from cryptography.hazmat.primitives.asymmetric import rsa

print("=== 3.1 Звичайний PRNG (модуль random) ===")
seed_value = 42

random.seed(seed_value)
seq1 = [random.randint(0, 255) for _ in range(8)]

random.seed(seed_value)
seq2 = [random.randint(0, 255) for _ in range(8)]

print(f"Seed: {seed_value}")
print(f"Запуск 1: {seq1}")
print(f"Запуск 2: {seq2}")
print(f"Послідовності ідентичні: {seq1 == seq2}\n")

print("=== 3.2 Криптографічно стійкий CSPRNG (модуль secrets) ===")
run1_keys = [secrets.token_hex(16) for _ in range(2)]
run2_keys = [secrets.token_hex(16) for _ in range(2)]

print(f"Запуск 1 (128-бітні ключі): {run1_keys}")
print(f"Запуск 2 (128-бітні ключі): {run2_keys}")
print(f"Ключі збігаються: {run1_keys == run2_keys}\n")

print("=== 4. Генерація асиметричних ключів RSA (2048 та 4096 біт) ===")
for key_size in [2048, 4096]:
    times = []
    for i in range(3):
        start = time.perf_counter()
        rsa.generate_private_key(public_exponent=65537, key_size=key_size)
        elapsed = time.perf_counter() - start
        times.append(elapsed)
        print(f"RSA-{key_size} | Спроба {i+1}: {elapsed:.4f} сек")
    avg_time = sum(times) / len(times)
    print(f"-> Середній час для RSA-{key_size}: {avg_time:.4f} сек\n")